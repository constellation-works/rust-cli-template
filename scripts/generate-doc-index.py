#!/usr/bin/env python3
"""Render docs/INDEX.md from the summary of every document STD-09 R15 covers.

STD-09 R16: the index is generated, never edited by hand, and CI fails when
the committed file differs from what this script renders (`--check`, in
`make docs-check`; `make doc-index` rewrites it). The documents and their
`summary` fields are read as `check-doc-frontmatter.py` reads them. The
documents of a feature's design folder are left out: the feature board,
docs/design/FEATURES.md, is their one entry. The index's own frontmatter keeps
its `created_date`, and moves `updated_date` to today only when the listing
changes, so `--check` compares the listing.
"""

import argparse
from datetime import date
from html import escape
from importlib.util import module_from_spec, spec_from_file_location
from pathlib import Path
import sys

SCRIPTS = Path(__file__).resolve().parent
ROOT = SCRIPTS.parent
INDEX = ROOT / "docs" / "INDEX.md"
SUMMARY = (
    "Every document at the repository root and under docs/ outside the feature design folders, "
    "with its one-line summary."
)


def sibling(name):
    """Load a sibling script as a module (their names are not identifiers)."""
    sys.dont_write_bytecode = True  # no __pycache__ beside the scripts
    spec = spec_from_file_location(name.replace("-", "_"), SCRIPTS / f"{name}.py")
    module = module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def feature_folder(path):
    """Whether a document sits in a feature's design folder (STD-09 R16).

    A feature folder is a directory directly under docs/design/ whose name does
    not start with `_` or `.`: the rule the feature board applies
    (generate-feature-board.py), so `_templates/` is not one.
    """
    parts = path.relative_to(ROOT).parts
    if len(parts) < 4 or parts[:2] != ("docs", "design"):
        return False
    return not parts[2].startswith(("_", "."))


def render(frontmatter):
    """The index's body: one section per directory, one line per document."""
    sections = {}
    for path in frontmatter.documents():
        if path == INDEX or feature_folder(path):
            continue
        rel = path.relative_to(ROOT)
        fields = frontmatter.frontmatter(path) or {}
        summary = escape(fields.get("summary", ""), quote=False)
        link = Path("..", rel).as_posix() if rel.parts[0] != "docs" else Path(*rel.parts[1:]).as_posix()
        heading = "Repository root" if len(rel.parts) == 1 else rel.parent.as_posix() + "/"
        sections.setdefault(heading, []).append(f"- [{rel.as_posix()}]({link}): {summary}")
    lines = [
        "# Documentation index",
        "",
        "Generated by `make doc-index` from each document's `summary`; do not edit it by hand.",
        "",
    ]
    for heading in sorted(sections, key=lambda name: (name != "Repository root", name)):
        lines += [f"## {heading}", "", *sections[heading], ""]
    return "\n".join(lines)


def with_frontmatter(body, created, updated):
    """The index: its frontmatter (STD-09 R15, R29), then the body."""
    return "\n".join(
        [
            "---",
            "type: index",
            f"summary: {SUMMARY}",
            f"created_date: {created}",
            f"updated_date: {updated}",
            "---",
            "",
            body,
        ]
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed index is stale")
    args = parser.parse_args()
    expected = render(sibling("check-doc-frontmatter"))
    current = sibling("generate-feature-board").existing(INDEX)
    if args.check:
        if current is None or current[0] != expected:
            raise SystemExit("docs/INDEX.md is stale: run make doc-index (STD-09 R16)")
        return
    today = date.today().isoformat()
    if current is None:
        created, updated = today, today
    else:
        body, created, updated = current
        if body != expected:
            updated = today
    INDEX.write_text(with_frontmatter(expected, created, updated), encoding="utf-8")


if __name__ == "__main__":
    main()
