#!/usr/bin/env python3
"""Render the feature board from the single-line entry document fields."""

import argparse
from datetime import date
from pathlib import Path
import re

DESIGN = Path(__file__).resolve().parent.parent / "docs" / "design"
STAGES = ("idea", "designing", "building", "shipped", "parked")


def entry_fields(path):
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0] != "---" or "---" not in lines[1:]:
        raise ValueError(f"{path.name}: missing frontmatter")
    fields = {}
    for line in lines[1:lines.index("---", 1)]:
        match = re.fullmatch(r"(owner|next|stage|title):\s*(\S.*)", line)
        if match:
            key, value = match.groups()
            value = value.strip()
            if value[0] in {"'", '"'} and value[0] == value[-1]:
                value = value[1:-1]
            fields[key] = value
    for key in ("owner", "next", "stage", "title"):
        if not fields.get(key):
            raise ValueError(f"{path.parent.name}/{path.name}: missing {key}")
    if fields["stage"] not in STAGES:
        raise ValueError(f"{path.parent.name}/{path.name}: unknown stage {fields['stage']!r}")
    return fields


def render():
    features = {stage: [] for stage in STAGES}
    for directory in sorted(DESIGN.iterdir()):
        if not directory.is_dir() or directory.name.startswith(("_", ".")):
            continue
        entries = [directory / name for name in ("1_scope.md", "1_overview.md")]
        entries = [path for path in entries if path.is_file()]
        if len(entries) != 1:
            raise ValueError(f"{directory.name}: expected exactly one design entry document")
        path = entries[0]
        fields = entry_fields(path)
        features[fields["stage"]].append((path.relative_to(DESIGN), fields))

    lines = [
        "# Feature board",
        "",
        "Generated by `make feature-board`.",
        "",
    ]
    for stage in STAGES:
        if not features[stage]:
            continue
        lines += [f"## {stage.capitalize()}", "", "| Feature | Owner | Next |", "| --- | --- | --- |"]
        for path, fields in features[stage]:
            title, owner, step = (fields[key].replace("|", r"\|") for key in ("title", "owner", "next"))
            lines.append(f"| [{title}]({path.as_posix()}) | {owner} | {step} |")
        lines.append("")
    return "\n".join(lines)


SUMMARY = "Every feature under docs/design/ by delivery stage, with its owner and next step."


def with_frontmatter(body, created, updated):
    """The board: its frontmatter (STD-09 R15, R29), then the body."""
    return "\n".join(
        [
            "---",
            "type: design",
            f"summary: {SUMMARY}",
            f"created_date: {created}",
            f"updated_date: {updated}",
            "---",
            "",
            body,
        ]
    )


def existing(board):
    """The committed board's body and its two dates, or None."""
    if not board.is_file():
        return None
    text = board.read_text(encoding="utf-8")
    match = re.match(
        r"---\n(?:.*\n)*?created_date: (\S+)\n(?:.*\n)*?updated_date: (\S+)\n(?:.*\n)*?---\n\n",
        text,
    )
    if not match:
        return None
    return text[match.end():], match.group(1), match.group(2)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the checked-in board is stale")
    args = parser.parse_args()
    try:
        expected = render()
    except ValueError as error:
        raise SystemExit(error) from error
    board = DESIGN / "FEATURES.md"
    current = existing(board)
    if args.check:
        if current is None or current[0] != expected:
            raise SystemExit("docs/design/FEATURES.md is stale: run make feature-board")
    else:
        today = date.today().isoformat()
        if current is None:
            created, updated = today, today
        else:
            body, created, updated = current
            if body != expected:
                updated = today
        board.write_text(with_frontmatter(expected, created, updated), encoding="utf-8")


if __name__ == "__main__":
    main()
